// The internal mapping of the ten roles (design REQ-010, section 7): the prompt
// appended to the system prompt of the executor and the tools of each role. A
// pure data module without Node API. It is never shown to the user: the views and
// the phrases take a role only through publicRole().
//
// "Only the current folder" is enforced by the flags of the process and its
// working folder, not by these texts; the texts are hints for the model.

const FILE_TOOLS = Object.freeze(["Read", "Write", "Edit", "Glob", "Grep"]);

function entry(prompt, tools = FILE_TOOLS) {
  return Object.freeze({ prompt, tools: Object.freeze([...tools]) });
}

